        extra = {
            chips0 = -10,
            chips = -10,
            chips2 = -10
        }
    },
    loc_txt = {
        ['name'] = 'taser',
        ['text'] = {
            [1] = 'Scored {C:attention}face{} cards become {C:attention}Electric{}',
            [2] = 'and {C:red}do not{} give their {C:attention}base Chips{}',
